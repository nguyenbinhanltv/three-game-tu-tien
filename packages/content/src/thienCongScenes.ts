// Bố cục rải PROP-1 "Thiên Công Khai Vật" cho 5 bản đồ: dữ liệu thuần cho `gen-thien-cong.ts` (không vào bundle client).
// Mỗi cảnh = một điểm nhìn/khu (tâm, bán kính) + số lượng từng món. Món thuộc nhóm nào do `tools/blender/prop_tc_items.json` quyết định.
// Tọa độ thế giới (m), +x đông, +z nam. Tâm lấy từ zones/pois/spawn của levels/<id>.json.

export interface Scene {
  /** Ghi chú ngắn: điểm nhìn/ý đồ. */
  note: string;
  at: [number, number];
  r: number;
  /** Bán kính trong (chừa tâm trống, ví dụ chỗ có sẵn điểm nhấn). */
  rMin?: number;
  /** tên món → số lượng. */
  items: Record<string, number>;
  /** Hướng mặt trước: về tâm cảnh, ra ngoài, hay ngẫu nhiên (mặc định). */
  face?: 'center' | 'out' | 'random';
  /** Cỡ tỉ lệ [min, max] (mặc định 0.9–1.15). */
  scale?: [number, number];
  /** Đảo/sàn: chỉ chấp nhận điểm có độ cao trong ±này so với độ cao tại tâm (m). */
  flat?: number;
  /** Bày tay: (dx, dz) từ tâm cảnh, yaw (0 = mặt trước +z), tỉ lệ, `v2` = biến thể 2. */
  fixed?: { name: string; dx: number; dz: number; yaw?: number; s?: number; v2?: boolean }[];
  /** Chọn tâm là các prop đặt tay (id) của level, mỗi món đặt cách tâm trong [nearR[0], nearR[1]] m: tinh thể/cột trận mọc quanh trụ đổ, tàn tích thay vì đứng lẻ giữa bãi. */
  nearBase?: string[];
  nearR?: [number, number];
  /** Rải theo cụm: số cụm (tâm cố định theo cảnh) và bán kính cụm (m, mặc định 22). */
  clusters?: number;
  clusterR?: number;
  /** Hàm loại điểm theo bố cục riêng (hành lang đường đi…). */
  avoid?: (x: number, z: number) => boolean;
}

